const fs = require('fs')
const path = require('path')
const archiver = require('archiver')
const builder = require('electron-builder')
const Arch = builder.Arch

const packageFile = require('./../package.json')
const version = packageFile.version
const appName = packageFile.productName || 'Prism'
const appSlug = packageFile.name || 'prism'

const createPackage = require('./createPackage.js')

async function afterPackageBuilt (packagePath) {
  /* create output directory if it doesn't exist */
  if (!fs.existsSync('dist/app')) {
    fs.mkdirSync('dist/app', { recursive: true })
  }

  let archSuffix

  if (packagePath.includes('arm64')) {
    archSuffix = '-arm64'
  } else {
    archSuffix = ''
  }

  /* create zip files */
  var output = fs.createWriteStream('dist/app/' + appName + '-v' + version + '-windows' + archSuffix + '.zip')
  var archive = archiver('zip', {
    zlib: { level: 9 }
  })
  archive.directory(packagePath, appName + '-v' + version)
  archive.pipe(output)
  await archive.finalize()

  // Look for NSIS installer generated by electron-builder
  const nsisSetup = path.resolve('dist/app', `${appName}-${version}${archSuffix ? '-' + archSuffix.replace('-', '') : '-x64'}-setup.exe`)
  const targetSetup = path.resolve('dist/app', `${appSlug}-${version}${archSuffix}-setup.exe`)
  if (fs.existsSync(nsisSetup)) {
    if (fs.existsSync(targetSetup)) {
      fs.unlinkSync(targetSetup)
    }
    fs.copyFileSync(nsisSetup, targetSetup)
    console.log('NSIS Installer ready: ' + targetSetup)
    return
  }

  /* create installer fallback (Squirrel) */
  const installer = require('electron-installer-windows')

  const destFolder = appSlug + '-installer' + archSuffix
  const destPath = 'dist/app/' + destFolder

  const options = {
    src: packagePath,
    dest: destPath,
    icon: 'icons/icon256.ico',
    animation: 'icons/windows-installer.gif',
    licenseUrl: 'https://github.com/minbrowser/min/blob/master/LICENSE.txt',
    noMsi: true
  }

  console.log('Creating installer package for ' + appName + ' ' + (archSuffix ? archSuffix.replace('-', '') : 'x64') + ' (this may take a while)...')

  fs.copyFileSync('LICENSE.txt', packagePath + '/LICENSE')

  await installer(options)
    .then(function () {
      const fullDestPath = path.resolve(destPath)
      if (fs.existsSync(fullDestPath)) {
        const exeFiles = fs.readdirSync(fullDestPath).filter(f => f.endsWith('.exe'))
        if (exeFiles.length > 0) {
          const generatedExe = path.join(fullDestPath, exeFiles[0])
          const finalExeName = './dist/app/' + appSlug + '-' + version + archSuffix + '-setup.exe'
          if (fs.existsSync(finalExeName)) {
            fs.unlinkSync(finalExeName)
          }
          fs.renameSync(generatedExe, finalExeName)
          console.log('Installer ready: ' + finalExeName)
        }
      }
    })
    .catch(err => {
      console.error(err, err.stack)
      process.exit(1)
    })
}

// Check for target architecture argument (e.g., node buildWindows.js --arch=x64)
const archArg = process.argv.find(arg => arg.startsWith('--arch='))
const targetArch = archArg ? archArg.split('=')[1].toLowerCase() : null

if (targetArch === 'x64') {
  createPackage('win32', { arch: Arch.x64, targets: ['dir', 'nsis'] }).then(afterPackageBuilt)
} else if (targetArch === 'arm64') {
  createPackage('win32', { arch: Arch.arm64, targets: ['dir', 'nsis'] }).then(afterPackageBuilt)
} else {
  // creating multiple packages simultaneously causes errors in electron-rebuild, so do one arch at a time instead
  createPackage('win32', { arch: Arch.x64, targets: ['dir', 'nsis'] })
    .then(afterPackageBuilt)
    .then(function () {
      return createPackage('win32', { arch: Arch.arm64, targets: ['dir', 'nsis'] })
    })
    .then(afterPackageBuilt)
}

